/** Pruebas del GPS didáctico y su relación consistente con los ticks. */
import assert from 'node:assert/strict';
import {createMission,startMission,advanceMission,routeProgress,etaMinutes,currentRoute} from '../src/simulation/navigation';
const initial = createMission('norte');
assert.equal(initial.active,false);
assert.equal(initial.distanceKm,0);
assert.equal(routeProgress(initial),0);
const started=startMission('norte',60);
assert.equal(started.active,true);
const tick1=advanceMission(started,true);
assert.equal(tick1.distanceKm,1);
assert.equal(tick1.elapsedMin,1);
assert.notEqual(tick1.latitude,started.latitude);
assert.equal(etaMinutes(tick1),Math.ceil((currentRoute('norte').km-1)/60*60));
const gpsFail=advanceMission(tick1,false);
assert.equal(gpsFail.signal,'SIN_GPS');
assert.equal(gpsFail.latitude,tick1.latitude);
assert.equal(gpsFail.longitude,tick1.longitude);
assert.equal(gpsFail.distanceKm,2);
const recovered=advanceMission(gpsFail,true);
assert.notEqual(recovered.latitude,gpsFail.latitude);
assert.equal(recovered.signal,'RTK');
let completed=startMission('centro',85);
for(let i=0;i<30;i++)completed=advanceMission(completed,true);
assert.equal(completed.completed,true);
assert.equal(completed.active,false);
assert.equal(completed.distanceKm,currentRoute('centro').km);
assert.equal(routeProgress(completed),1);
assert.equal(advanceMission(completed,true).elapsedMin,completed.elapsedMin);
console.log('OK V11: ruta, reloj, coordenadas, falla GPS, recuperación y llegada.');
