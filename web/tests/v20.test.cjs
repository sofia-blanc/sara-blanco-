/** AUTOOS V20: reglas puras y contrato UI sin interrupción por clic. */
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {routeIndexFromLane,minutesToDrivingFork,forkVisibleWhileDriving}=require('../src/simulation/routeDrivingV20.ts');
for(let lane=0;lane<3;lane++)assert.equal(routeIndexFromLane(lane,3),lane,'Tres rutas siguen carril físico');
assert.equal(routeIndexFromLane(0,2),0);
assert.equal(routeIndexFromLane(1,2),0,'Centro elige primera ruta en cruce doble');
assert.equal(routeIndexFromLane(2,2),1);
assert.equal(routeIndexFromLane(1,1),0);
assert.equal(routeIndexFromLane(0,0),-1);
assert.equal(minutesToDrivingFork(2,0),3);
assert.equal(minutesToDrivingFork(5,0),0);
assert.equal(minutesToDrivingFork(5,1),5);
assert.equal(minutesToDrivingFork(9,1),1);
assert.equal(minutesToDrivingFork(15,2),0);
assert.equal(forkVisibleWhileDriving(2,0,true),true,'Aviso tres minutos antes');
assert.equal(forkVisibleWhileDriving(1,0,true),false);
assert.equal(forkVisibleWhileDriving(5,0,false),false,'No mostrar preview si hay parada');
const scene=fs.readFileSync(path.join(__dirname,'../src/components/MissionStageV17.tsx'),'utf8');
assert.match(scene,/AUTOOS_V20_SIN_CLIC|AUTOOS_V21_CRUCES_LIMITADOS/);
assert.match(scene,/window\.addEventListener\('keydown',handleKey\)/);
assert.doesNotMatch(scene,/onClick=\{\(\)=>p\.onSelect\(/,'No rutas seleccionadas con clic');
assert.doesNotMatch(scene,/La conducción está pausada\. Elige una vía/);
const center=fs.readFileSync(path.join(__dirname,'../src/components/SimulationCenter.tsx'),'utf8');
assert.match(center,/AUTOOS_V20_CRUCES_SIN_PAUSA/);
assert.match(center,/autoCheckpointRef\.current === (?:checkpointMinute|junctionMinute)/);
assert.match(center,/choose\(selectedRoute\.id\)/);
assert.doesNotMatch(center,/if \(checkpointDue && running\) setRunning\(false\)/);
console.log('OK V20: 2/3 rutas por carril, avisos anticipados, sin botones de selección ni pausa forzada.');
